export function setI18nLanguage(lang: BahasaAktif): void {
  const targetLng = lang === 'aks' ? 'jw' : lang;
  if (i18next.language !== targetLng) {
    void i18next.changeLanguage(targetLng);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'en' ? 'en' : lang === 'id' ? 'id' : 'jv';
  }
}

export function tI18n(
  lang: BahasaAktif,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const lngCode = lang === 'aks' ? 'jw' : lang;
  const fixed = i18next.getFixedT(lngCode);
  const raw = String(vars ? fixed(key, vars as never) : fixed(key as never));
  if (lang === 'aks') {
    return konversiTeksKeAksaraAman(raw);
  }
  return raw;
}
